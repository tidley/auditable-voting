//! Shared native and browser blind-credential primitives.
//!
//! The protocol remains RSABSSA-SHA384-PSS-Deterministic: deterministic
//! *message preparation*, with a fresh 48-byte PSS salt for each blinding.
//! Message/domain encoding and persisted key IDs belong to the callers.

use base64::{engine::general_purpose::URL_SAFE_NO_PAD, Engine as _};
use blind_rsa_signatures::{
    reexports::{
        crypto_bigint::BoxedUint,
        rsa::{traits::PublicKeyParts, PrivateKey as RsaPrivateKey, PublicKey as RsaPublicKey},
    },
    BlindMessage, BlindSignature, BlindingResult, DefaultRng, PublicKeySha384PSSDeterministic,
    Secret, SecretKeySha384PSSDeterministic, Signature,
};
use serde_json::Value;

pub const SCHEME: &str = "rsabssa-sha384-pss-deterministic-v1";
pub const MAX_MESSAGE_BYTES: usize = 1024 * 1024;

#[derive(Debug, thiserror::Error)]
pub enum Error {
    #[error("Invalid or unsupported RSA JWK.")]
    InvalidKey,
    #[error("Invalid RSA representative or hexadecimal encoding.")]
    InvalidEncoding,
    #[error("Blind-credential operation failed.")]
    Crypto,
    #[error("Blind-credential message exceeds the size limit.")]
    MessageTooLarge,
}

pub struct PublicKey(PublicKeySha384PSSDeterministic);

// Do not derive Debug/Serialize: the inverse is a private voter secret.
pub struct Blinding {
    pub blinded_message: Vec<u8>,
    pub blinding_factor: Vec<u8>,
}

fn component(jwk: &Value, field: &str) -> Result<BoxedUint, Error> {
    let encoded = jwk
        .get(field)
        .and_then(Value::as_str)
        .ok_or(Error::InvalidKey)?;
    // Bounds apply before base64 decoding or expensive RSA arithmetic.
    if encoded.is_empty() || encoded.len() > 684 {
        return Err(Error::InvalidKey);
    }
    let bytes = URL_SAFE_NO_PAD
        .decode(encoded)
        .map_err(|_| Error::InvalidKey)?;
    if bytes.is_empty() || bytes.len() > 512 {
        return Err(Error::InvalidKey);
    }
    Ok(BoxedUint::from_be_slice_vartime(&bytes))
}

fn public_rsa(jwk: &Value) -> Result<RsaPublicKey, Error> {
    if jwk.get("kty").is_some_and(|value| value != "RSA") {
        return Err(Error::InvalidKey);
    }
    let n = component(jwk, "n")?;
    let e = component(jwk, "e")?;
    // 3072-bit keys are generated by the shipped app. Retain 1024-bit legacy
    // import compatibility; accepting an old key is not a strength endorsement.
    if !(1024..=4096).contains(&n.bit_width()) || e.bit_width() > 64 {
        return Err(Error::InvalidKey);
    }
    RsaPublicKey::new(n, e).map_err(|_| Error::InvalidKey)
}

impl PublicKey {
    pub fn from_jwk(jwk: &Value) -> Result<Self, Error> {
        Ok(Self(PublicKeySha384PSSDeterministic::new(public_rsa(jwk)?)))
    }

    fn representative(&self, bytes: &[u8]) -> Result<(), Error> {
        let rsa: &RsaPublicKey = self.0.as_ref();
        if bytes.len() != rsa.size() {
            return Err(Error::InvalidEncoding);
        }
        let value = BoxedUint::from_be_slice_vartime(bytes);
        if bool::from(value.is_zero()) || &value >= rsa.n().as_ref() {
            return Err(Error::InvalidEncoding);
        }
        Ok(())
    }

    pub fn blind(&self, message: &[u8]) -> Result<Blinding, Error> {
        message_limit(message)?;
        let result = self
            .0
            .blind(&mut DefaultRng, message)
            .map_err(|_| Error::Crypto)?;
        Ok(Blinding {
            blinded_message: result.blind_message.0,
            blinding_factor: result.secret.0,
        })
    }

    pub fn finalize(
        &self,
        message: &[u8],
        signed: &[u8],
        inverse: &[u8],
    ) -> Result<Vec<u8>, Error> {
        message_limit(message)?;
        self.representative(signed)?;
        self.representative(inverse)?;
        // Finalisation needs only the inverse from the existing saved request.
        // The Rust library does not use blind_message during finalisation.
        let result = BlindingResult {
            blind_message: BlindMessage(Vec::new()),
            secret: Secret(inverse.to_vec()),
            msg_randomizer: None,
        };
        self.0
            .finalize(&BlindSignature(signed.to_vec()), &result, message)
            .map(|sig| sig.0)
            .map_err(|_| Error::Crypto)
    }

    pub fn verify(&self, message: &[u8], signature: &[u8]) -> bool {
        message_limit(message).is_ok()
            && self.representative(signature).is_ok()
            && self
                .0
                .verify(&Signature(signature.to_vec()), None, message)
                .is_ok()
    }
}

fn message_limit(message: &[u8]) -> Result<(), Error> {
    if message.len() > MAX_MESSAGE_BYTES {
        Err(Error::MessageTooLarge)
    } else {
        Ok(())
    }
}

pub fn sign(private_jwk: &Value, blinded: &[u8]) -> Result<Vec<u8>, Error> {
    let public = PublicKey::from_jwk(private_jwk)?;
    public.representative(blinded)?;
    let rsa = public_rsa(private_jwk)?;
    let mut private = RsaPrivateKey::from_components(
        rsa.n().as_ref().clone(),
        rsa.e().clone(),
        component(private_jwk, "d")?,
        vec![component(private_jwk, "p")?, component(private_jwk, "q")?],
    )
    .map_err(|_| Error::InvalidKey)?;
    private.validate().map_err(|_| Error::InvalidKey)?;
    private.precompute().map_err(|_| Error::InvalidKey)?;
    // Library implementation uses RSA blinding and verifies the CRT result.
    // Never perform a raw unblinded private exponentiation here.
    SecretKeySha384PSSDeterministic::new(private)
        .blind_sign(blinded)
        .map(|sig| sig.0)
        .map_err(|_| Error::Crypto)
}

pub fn decode_hex(input: &str) -> Result<Vec<u8>, Error> {
    let input = input.trim();
    if input.is_empty() || input.len() > 1024 || input.len() % 2 != 0 || !input.bytes().all(|byte| byte.is_ascii_hexdigit()) {
        return Err(Error::InvalidEncoding);
    }
    input
        .as_bytes()
        .chunks_exact(2)
        .map(|pair| {
            let s = std::str::from_utf8(pair).map_err(|_| Error::InvalidEncoding)?;
            u8::from_str_radix(s, 16).map_err(|_| Error::InvalidEncoding)
        })
        .collect()
}

pub fn encode_hex(bytes: &[u8]) -> String {
    bytes.iter().map(|byte| format!("{byte:02x}")).collect()
}

#[cfg(feature = "wasm")]
mod wasm {
    use super::*;
    use wasm_bindgen::prelude::*;

    fn key(json: &str) -> Result<Value, JsValue> {
        if json.len() > 16_384 {
            return Err(js(Error::InvalidKey));
        }
        serde_json::from_str(json).map_err(|_| js(Error::InvalidKey))
    }
    fn js(error: Error) -> JsValue {
        JsValue::from_str(&error.to_string())
    }

    #[wasm_bindgen]
    pub fn blind_credential_blind(jwk: &str, message: &[u8]) -> Result<String, JsValue> {
        let result = PublicKey::from_jwk(&key(jwk)?)
            .map_err(js)?
            .blind(message)
            .map_err(js)?;
        Ok(serde_json::json!({ "blindedMessage": encode_hex(&result.blinded_message), "blindingFactor": encode_hex(&result.blinding_factor) }).to_string())
    }
    #[wasm_bindgen]
    pub fn blind_credential_sign(jwk: &str, blinded: &str) -> Result<String, JsValue> {
        sign(&key(jwk)?, &decode_hex(blinded).map_err(js)?)
            .map(|bytes| encode_hex(&bytes))
            .map_err(js)
    }
    #[wasm_bindgen]
    pub fn blind_credential_finalize(
        jwk: &str,
        message: &[u8],
        signed: &str,
        inverse: &str,
    ) -> Result<String, JsValue> {
        PublicKey::from_jwk(&key(jwk)?)
            .map_err(js)?
            .finalize(
                message,
                &decode_hex(signed).map_err(js)?,
                &decode_hex(inverse).map_err(js)?,
            )
            .map(|bytes| encode_hex(&bytes))
            .map_err(js)
    }
    #[wasm_bindgen]
    pub fn blind_credential_verify(jwk: &str, message: &[u8], signature: &str) -> bool {
        let Ok(jwk) = key(jwk) else {
            return false;
        };
        let Ok(public) = PublicKey::from_jwk(&jwk) else {
            return false;
        };
        let Ok(signature) = decode_hex(signature) else {
            return false;
        };
        public.verify(message, &signature)
    }
}
