import { test, expect } from '@playwright/test';

test('detailed offline demo preserves live state and never opens transports', async ({ page, context }) => {
  await page.addInitScript(() => {
    localStorage.setItem('demo-test-live-state', 'keep-existing-election');
    sessionStorage.setItem('demo-test-live-session', 'keep-existing-session');
    const deny = () => { throw new Error('Sandbox attempted a live transport'); };
    for (const name of ['WebSocket', 'EventSource', 'Worker', 'SharedWorker', 'RTCPeerConnection'] as const) {
      Object.defineProperty(window, name, { value: deny, configurable: true });
    }
    window.fetch = deny;
    navigator.sendBeacon = deny;
    const getItem = Storage.prototype.getItem;
    const setItem = Storage.prototype.setItem;
    Storage.prototype.getItem = function (key) { return key === 'av-theme' ? getItem.call(this, key) : deny(); };
    Storage.prototype.setItem = function (key, value) { return key === 'av-theme' ? setItem.call(this, key, value) : deny(); };
    Storage.prototype.removeItem = deny;
    Storage.prototype.clear = deny;
  });
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/demo.html');
  await expect(page.getByRole('heading', { name: 'Prepare the election', exact: true })).toBeVisible();
  const before = await page.evaluate(() => ({ local: { ...localStorage }, session: { ...sessionStorage } }));
  const connections: string[] = [];
  page.on('request', request => { if (['fetch', 'xhr', 'websocket', 'eventsource', 'ping'].includes(request.resourceType())) connections.push(request.url()); });
  await context.setOffline(true);
  await page.getByRole('button', { name: 'Review questionnaire', exact: true }).click();
  await page.getByRole('button', { name: 'Go Live', exact: true }).click();
  await page.getByLabel('Paper code', { exact: true }).fill('WRONG');
  await page.getByLabel('Master-list number', { exact: true }).fill('1042');
  await page.getByRole('button', { name: 'Request ballot', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Admission refused');
  await page.getByRole('button', { name: 'Fill example values' }).click();
  await page.getByRole('button', { name: 'Request ballot', exact: true }).click();
  await page.getByRole('radio', { name: 'Yes', exact: true }).check();
  await expect(page.getByLabel('Which plot would you prefer?')).toBeVisible();
  await page.getByLabel('Which plot would you prefer?').selectOption('north');
  await page.getByRole('radio', { name: 'No', exact: true }).check();
  await expect(page.getByLabel('Which plot would you prefer?')).toHaveCount(0);
  await page.getByRole('radio', { name: 'Yes', exact: true }).check();
  await page.getByLabel('Which plot would you prefer?').selectOption('north');
  await page.getByLabel('Deliberately lose the intake receipt').check();
  await page.getByRole('button', { name: 'Submit response', exact: true }).click();
  await page.getByRole('button', { name: 'Voter', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Voter demo workspace' })).toContainText('Awaiting worker receipt');
  await page.getByRole('button', { name: 'Observer', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Observer demo workspace' })).toContainText('No public ballots yet');
  await page.getByRole('button', { name: 'Worker', exact: true }).click();
  await page.getByRole('button', { name: 'Retry same submission / recover receipt' }).click();
  await page.getByRole('button', { name: 'Explore threshold release' }).click();
  await page.getByRole('button', { name: 'Add next anonymous example ballot' }).click();
  await expect(page.getByRole('button', { name: 'Add next anonymous example ballot' })).toBeFocused();
  await page.getByRole('button', { name: 'Add next anonymous example ballot' }).click();
  await page.getByRole('button', { name: 'Queue final anonymous ballot' }).click();
  await page.getByRole('button', { name: 'Advance clock to deadline' }).click();
  await expect(page.getByRole('status')).toContainText('publication failure');
  await page.getByRole('button', { name: 'Simulate worker restart', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('not a real process restart');
  await page.getByRole('button', { name: 'Retry prepared batch' }).click();
  await page.getByRole('button', { name: 'Try a late ballot' }).click();
  await expect(page.getByRole('button', { name: 'Try a late ballot' })).toBeFocused();
  await page.getByRole('button', { name: 'Try a duplicate ballot' }).click();
  await page.getByRole('button', { name: 'Check simulated records' }).click();
  await expect(page.getByRole('heading', { name: 'Reconcile and repeat', exact: true })).toBeVisible();
  await expect(page.getByRole('region', { name: 'Observer demo workspace' })).toContainText('Yes 3 · No 1');
  await expect(page.getByRole('table').locator('tbody tr')).toHaveCount(4);
  await page.getByRole('button', { name: 'Reset and repeat the demo' }).click();
  await expect(page.getByRole('heading', { name: 'Prepare the election', exact: true })).toBeFocused();
  expect(await page.evaluate(() => ({ local: { ...localStorage }, session: { ...sessionStorage } }))).toEqual(before);
  expect(connections).toEqual([]);
  expect(errors).toEqual([]);
});

test('sandbox layout, keyboard navigation, reload and CSP are isolated', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 });
  await page.goto('/demo.html');
  const csp = await page.locator('meta[http-equiv="Content-Security-Policy"]').getAttribute('content');
  expect(csp).toContain("connect-src 'none'");
  expect(csp).toContain("form-action 'none'");
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth);
  expect(overflow).toBe(false);
  await page.keyboard.press('Tab');
  await expect(page.getByRole('link', { name: 'Skip to demo workspace' })).toBeFocused();
  await page.getByRole('button', { name: 'Review questionnaire', exact: true }).click();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Prepare the election', exact: true })).toBeVisible();
  const scripts = await page.locator('script[src]').evaluateAll(nodes => nodes.map(node => node.getAttribute('src')));
  expect(scripts).toEqual(['./demo-theme.js', './demo-sandbox.js']);
});

test('demo shares only the persisted theme preference, not election state', async ({ page }) => {
  await page.goto('/demo.html');
  await page.getByRole('button', { name: 'Switch to dark theme', exact: true }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  expect(await page.evaluate(() => localStorage.getItem('av-theme'))).toBe('dark');
  await page.getByRole('button', { name: 'Review questionnaire', exact: true }).click();
  await page.reload();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await expect(page.getByRole('heading', { name: 'Prepare the election', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Switch to light theme', exact: true }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  expect(await page.evaluate(() => localStorage.getItem('av-theme'))).toBe('light');
  await page.setViewportSize({ width: 375, height: 812 });
  const help = await page.getByRole('link', { name: 'How it works', exact: true }).boundingBox();
  const toggle = await page.getByRole('button', { name: 'Switch to dark theme', exact: true }).boundingBox();
  expect(toggle!.x).toBeGreaterThanOrEqual(help!.x + help!.width);
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
});

